def capex_path(year, case="主", start=48_000.0):
    """参入年 year の資本費（円/kWh、4時間、実質2025年価格）。2045年以降は2045年の値で一定"""
    i = min(max(int(year), 2025), 2045) - 2025
    idx = {"主": _IEA[i] / _IEA[0], "低位": _NREL_LO[i] / _NREL_LO[0], "高位": _NREL_HI[i] / _NREL_HI[0]}[case]
    return start * idx


def set_eta(m41, eta=ETA):
    """41 の部品の往復効率を差し替え、実績の戦略c（C_ACT）と完全予見（PF_ACT）を計算し直す"""
    m41["ETA"] = eta
    d = m41["daily_eval"](m41["PACTM"], m41["W_M"])
    m41["C_ACT"] = m41["annual"](d["c"], m41["FYM"], m41["EV"])
    m41["PF_ACT"] = m41["annual"](d["pf"], m41["FYM"], m41["EV"])
    return m41["C_ACT"]
