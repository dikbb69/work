ETA = 0.90
LOSS = 1.0 - ETA
CRF20 = 0.06 * 1.06 ** 20 / (1.06 ** 20 - 1)
OM = 5_300.0                                                    # 旧（運転維持＋廃止の近似）。新しい計算は OM_BASE と decom()
OM_BASE = 5_000.0
CHG_KWH = 4 * 365
NET_FIX = 12 * (LOSS * 628.10 + (1 - LOSS) * 137.50) / 1.1
W_LOSS = CHG_KWH * LOSS * (1.02 + 4.18) / 1.1
W_FULL = CHG_KWH * (LOSS * 1.02 + 4.18) / 1.1
CAPEX = {"6.8万": 68_000.0, "4.0万": 40_000.0, "2.3万": 23_000.0}
KP_COL = "κP 全国連系・起点1.25万・2030年度向け近似（主）(円/kW-年)"
KP_COL_OLD = "κP 北海道ブロック按分・起点1.25万・2030年度向け近似（主）(円/kW-年)"
KP_SCALE = 0.861 / 0.836


def c_req(capex, net_fix=NET_FIX):
    return capex * 4 * CRF20 + OM + net_fix


def decom(capex):
    """廃止費（建設費の5%、20年目に支払う）の年額（円/kW-年）"""
    return 0.05 * capex * 4 / 1.06 ** 20 * CRF20


def c_req_v5(capex, net_fix=NET_FIX):
    """年間の必要収益（円/kW-年）＝資本費の年額＋運転維持費5,000＋廃止費の年額＋託送等の固定費"""
    return capex * 4 * CRF20 + OM_BASE + decom(capex) + net_fix


