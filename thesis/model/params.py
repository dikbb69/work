def scenario_year(y, sc):
    """年 y の需給の前提（MW・GWh）"""
    key = sc["y2040"]
    dem = interp_year({**DEMAND_GWH, 2040: DEMAND_2040[key]}, y)
    dc = interp_year({**{k: v for k, v in DC_GWH.items() if k != 2040}, 2040: DC_GWH[2040][key]}, y)
    s35, w35 = SOLAR_MW[2035], WIND_MW[2035]
    s40 = SOLAR_X3 if sc.get("solar_x3") else Y2040[key]["solar"]
    if y <= 2035:
        solar, selfc = interp_year(SOLAR_MW, y), 0.0
        wind = interp_year(WIND_MW, y)
    else:
        inc = max(s40 - s35, 0.0) * (y - 2035) / 5.0
        share = SELFCONS_SHARE[key]
        solar, selfc = s35 + (1 - share) * inc, share * inc
        wind = w35 + (Y2040[key]["wind"] - w35) * (y - 2035) / 5.0
    nuc = []                                                   # (ユニット, 運転を始める年度内の月。None は通年)
    if sc.get("nuclear", True):
        for u, (yy, mm) in NUC_START.items():
            if y > yy or (y == yy and mm == 4):
                nuc.append((u, None))
            elif y == yy:
                nuc.append((u, mm))                            # 年度の途中から（10月なら下期だけ）
    bio_add = sum(mw * 0.70 for yy, mw in BIOMASS_ADD.values() if y >= yy)
    geo_add = max(interp_year(GEO_MW, y) - GEO_MW[2025], 0.0)
    return dict(year=y, demand_gwh=dem, dc_gwh=dc, solar_mw=solar, wind_mw=wind, selfcons_mw=selfc, nuclear=nuc,
                biomass_add_mw=bio_add, geo_add_mw=geo_add, export_opcap=interp_year(EXPORT_OPCAP, y),
                export_increment_mw=EXPORT_INCREMENT_MW if (y >= 2028 and sc.get("export_increment", True)) else 0.0,
                surplus_export=sc.get("surplus_export", "market"))


