import numpy as np
import pandas as pd

REG = []


def P(name, value, unit, source, kind, note=""):
    REG.append(dict(name=name, value=value, unit=unit, source=source, kind=kind, note=note))
    return value


def table():
    return pd.DataFrame([{**r, "value": str(r["value"])} for r in REG])


def interp_year(table_, y):
    ys = sorted(table_)
    return float(np.interp(y, ys, [table_[k] for k in ys]))


