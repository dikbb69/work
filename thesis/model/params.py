def _toward_2040(y, y0, v0, v40):
    """y0 年の v0 から2040年の v40 まで直線（2040年より後は v40）"""
    return v0 + (v40 - v0) * min(max((y - y0) / (2040 - y0), 0.0), 1.0)


def scenario_year(y, sc):
    """年 y の需給の前提（MW・GWh）。主は足元（FY2025）から2040年の値まで直線（PATH）"""
    key = sc["y2040"]
    a = Y2040[key]
    share = SELFCONS_SHARE[key]
    if sc.get("path", PATH) == "plan" and y <= 2035:              # 頑健性: 2035年までは需要想定・供給計画
        dem, dc = interp_year(DEMAND_GWH, y), interp_year(DC_GWH, y)
        solar, selfc, wind = interp_year(SOLAR_MW, y), 0.0, interp_year(WIND_MW, y)
    elif sc.get("path", PATH) == "plan2035":                      # 主: 太陽光・風力は FY2035 まで供給計画、FY2035→2040 は直線。需要・DC は FY2025 から直線
        y0 = BASE_FY
        dem = _toward_2040(y, y0, DEMAND_GWH[y0], a["demand"])
        dc = _toward_2040(y, y0, 0.0, a["dc"])
        if y <= 2035:
            solar, selfc, wind = interp_year(SOLAR_MW, y), 0.0, interp_year(WIND_MW, y)
        else:                                                   # 2035年からの増分の31%を自家消費とする（2040年の値が2035年より小さいときは系統の分だけ減らす）
            inc = _toward_2040(y, 2035, 0.0, a["solar"] - SOLAR_MW[2035])
            solar, selfc = SOLAR_MW[2035] + (1 - share) * max(inc, 0.0) + min(inc, 0.0), share * max(inc, 0.0)
            wind = _toward_2040(y, 2035, WIND_MW[2035], a["wind"])
        if sc.get("selfcons_from") == 2025 and y > 2035:        # 確かめ: 自家消費を FY2025 からの増分の31%とする（2040年の合計は同じ）
            tot = solar + selfc
            selfc = share * max(tot - SOLAR_MW[2025], 0.0)
            solar = tot - selfc
    elif sc.get("path", PATH) == "plan":                          # 2036〜40年は2035年の値から直線（太陽光は2035年を下回るなら据え置き）
        dem = _toward_2040(y, 2035, DEMAND_GWH[2035], a["demand"])
        dc = _toward_2040(y, 2035, DC_GWH[2035], a["dc"])
        inc = _toward_2040(y, 2035, 0.0, max(a["solar"] - SOLAR_MW[2035], 0.0))
        solar, selfc = SOLAR_MW[2035] + (1 - share) * inc, share * inc
        wind = _toward_2040(y, 2035, WIND_MW[2035], a["wind"])
    else:                                                       # linear（旧の主）: FY2025 から2040年まで直線
        y0 = BASE_FY
        dem = _toward_2040(y, y0, DEMAND_GWH[y0], a["demand"])
        dc = _toward_2040(y, y0, 0.0, a["dc"])
        inc = _toward_2040(y, y0, 0.0, max(a["solar"] - SOLAR_MW[y0], 0.0))
        solar, selfc = SOLAR_MW[y0] + (1 - share) * inc, share * inc
        wind = _toward_2040(y, y0, WIND_MW[y0], a["wind"])
    nuc = []                                                   # (ユニット, 運転を始める年度内の月。None は通年)
    for u in NUC_CASES[sc.get("nuclear", "3号だけ")]:
        yy, mm = NUC_START[u]
        if y > yy or (y == yy and mm == 4):
            nuc.append((u, None))
        elif y == yy:
            nuc.append((u, mm))                                # 年度の途中から（10月なら下期だけ）
    bio_add = sum(mw * 0.70 for yy, mw in BIOMASS_ADD.values() if y >= yy)
    geo_add = max(interp_year(GEO_MW, y) - GEO_MW[2025], 0.0)
    age = sc.get("retire_age")
    retire = tuple(u[0] for u in UNITS if age is not None and u[8] >= 2100 and y > u[7] + age)   # 公表済みの廃止がある号機はそちら
    return dict(year=y, demand_gwh=dem, dc_gwh=dc, solar_mw=solar, wind_mw=wind, selfcons_mw=selfc, nuclear=nuc,
                biomass_add_mw=bio_add, geo_add_mw=geo_add, export_opcap=interp_year(EXPORT_OPCAP, y),
                export_increment_mw=EXPORT_INCREMENT_MW if (y >= 2028 and sc.get("export_increment", True)) else 0.0,
                surplus_export=sc.get("surplus_export", "market"), retire=retire)


