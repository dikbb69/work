def add_image(src, name):
    shutil.copy(src, DST + '/word/media/' + name)
    rels = DST + '/word/_rels/document.xml.rels'
    x = open(rels, encoding='utf-8').read()
    ids = [int(i) for i in re.findall(r'Id="rId(\d+)"', x)]
    rid = 'rId%d' % (max(ids) + 1)
    x = x.replace('</Relationships>', '<Relationship Id="%s" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="media/%s"/></Relationships>' % (rid, name))
    open(rels, 'w', encoding='utf-8').write(x)
    return rid


