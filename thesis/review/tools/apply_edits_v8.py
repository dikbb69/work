# ------------------------------------------------------------------ TOC helpers
def toc_lines():
    return [p for p in body if p.tag == q('w:p') and style_of(p) in ('11', '21') and p.find(q('w:hyperlink')) is not None]


def toc_find(prefix):
    for p in toc_lines():
        h = p.find(q('w:hyperlink'))
        if norm(ptext(h)).startswith(norm(prefix)):
            return p
    raise KeyError('toc ' + prefix)


def toc_text(p):
    return ptext(p.find(q('w:hyperlink'))).split('\t')[0]


def toc_set(prefix, markup):
    p = toc_find(prefix)
    h = p.find(q('w:hyperlink'))
    segs = segs_of(h)
    like = [s for s in segs if s[0] == 't'][0][2]
    tail = [s for s in segs if s[0] == 'o']
    rebuild(h, parse_markup(markup, like, True) + tail)


def toc_new(after_prefix, anchor, markup, template_prefix=None):
    """clone a TOC line (never the first one of a field) and insert it after the line starting with after_prefix"""
    ref = toc_find(after_prefix)
    tpl = toc_find(template_prefix or after_prefix)
    if any(r.find(q('w:instrText')) is not None and 'TOC' in (r.find(q('w:instrText')).text or '') for r in tpl.findall(q('w:r'))):
        raise ValueError('template is the first TOC line: ' + after_prefix)
    new = strip_ids(copy.deepcopy(tpl))
    h = new.find(q('w:hyperlink'))
    h.set(q('w:anchor'), anchor)
    for it in h.iter(q('w:instrText')):
        it.text = ' PAGEREF %s \\h ' % anchor
    segs = segs_of(h)
    like = [s for s in segs if s[0] == 't'][0][2]
    tail = [s for s in segs if s[0] == 'o']
    rebuild(h, parse_markup(markup, like, True) + tail)
    ref.addnext(new)
    return new


