# ------------------------------------------------------------------ lookup helpers
def all_pars(scope=None):
    return list((scope if scope is not None else body).iter(q('w:p')))


def find(prefix, nth=0, scope=None):
    k = norm(prefix)
    hits = [p for p in all_pars(scope) if norm(ptext(p)).startswith(k)]
    if len(hits) <= nth:
        raise KeyError('paragraph not found: %r (hits=%d)' % (prefix, len(hits)))
    return hits[nth]


def heading(prefix):
    for p in body:
        if p.tag == q('w:p') and p.find(q('w:pPr')) is not None:
            st = p.find(q('w:pPr')).find(q('w:pStyle'))
            if st is not None and st.get(q('w:val')) in ('1', '2', '3') and norm(ptext(p)).startswith(norm(prefix)):
                return p
    raise KeyError(prefix)


def style_of(p):
    pr = p.find(q('w:pPr'))
    st = pr.find(q('w:pStyle')) if pr is not None else None
    return st.get(q('w:val')) if st is not None else ''


def next_el(el, n=1):
    for _ in range(n):
        el = el.getnext()
    return el


def table_after(p):
    e = p.getnext()
    while e is not None and e.tag != q('w:tbl'):
        e = e.getnext()
    return e


