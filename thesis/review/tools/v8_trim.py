"""v8 (second round): cuts that shorten the text.

Executed inside apply_edits_v8.py with exec(), so it uses that script's helpers (find, sub, remove, ...).
A pure deletion leaves no colour in the document; a reworded piece is blue (‹…›).
Every cut is recorded in TRIM and written to out/v8_trim_log.tsv for the change log.
"""
TRIM = []          # (section, kind, removed text, replacement)


def cut(prefix, old, new='', sec='', nth=0):
    p = find(prefix, nth)
    sub(p, old, new)
    TRIM.append((sec, 'rewrite' if new else 'cut', old, new))
    return p


def drop_par(prefix, sec='', nth=0):
    p = find(prefix, nth)
    nxt = p.getnext()
    TRIM.append((sec, 'paragraph', ptext(p), ''))
    was_first = style_of(p) == 'FirstParagraph'
    remove(p)
    if was_first and nxt is not None and nxt.tag == q('w:p') and style_of(nxt) == 'a0':
        set_style(nxt, 'FirstParagraph')
    return nxt


